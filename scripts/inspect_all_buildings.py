"""Summarize the metadata of every building in configs/splits.yaml.

Run from the repo root (about 1 minute per building):
    python scripts/inspect_all_buildings.py

Writes docs/building_summary.md and docs/building_summary.csv.
"""
import csv
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from smart_buildings.evaluate import create_building_meta_data, load_hybrid_environment
from src.features import BuildingIndex

ROOT = Path(__file__).resolve().parents[1]


def main():
    splits = yaml.safe_load(open(ROOT / "configs" / "splits.yaml", encoding="utf-8"))
    rows = []
    for split, buildings in splits.items():
        for building, weathers in buildings.items():
            weather = weathers[0]
            config = ROOT / "smart_buildings" / "training_scenarios" / building / weather / "config.gin"
            print(f"loading {building} / {weather} ...", flush=True)
            env = load_hybrid_environment(config)
            meta = create_building_meta_data(env, config.parent)
            idx = BuildingIndex(meta)
            K, V = idx.num_ahus, idx.num_zones
            zones_per_ahu = [len(v) for v in meta["ahu_zone_assignments"].values()]
            rows.append({
                "split": split, "building": building, "weather_loaded": weather,
                "K_ahu": K, "V_zone": V, "obs_len": len(meta["observation_field_names"]),
                "n_cont": meta["n_continuous_action"], "n_disc": meta["n_discrete_action"],
                "formula_ok": (3 * K + 2 + 2 * V == meta["n_continuous_action"]
                               and K + 1 == meta["n_discrete_action"]),
                "floors": meta["num_floors"],
                "floor_plan_shape": "x".join(str(s) for s in meta["floor_plan"].shape),
                "zones_per_ahu": "/".join(str(z) for z in zones_per_ahu),
                "comfort_window": str(meta["comfort_temp_window"]),
                "eco_window": str(meta["eco_temp_window"]),
                "morning_start_hour": meta["morning_start_hour"],
                "evening_start_hour": meta["evening_start_hour"],
                "time_zone": meta["time_zone"], "num_holidays": len(meta["holidays"]),
            })
            print("  ", rows[-1], flush=True)

    out_csv = ROOT / "docs" / "building_summary.csv"
    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    cols = list(rows[0])
    lines = ["# Building summary (generated by scripts/inspect_all_buildings.py)", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    (ROOT / "docs" / "building_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/building_summary.md and docs/building_summary.csv")


if __name__ == "__main__":
    main()
